    def expire_old_signals(
        self, strategy_id: Optional[int] = None, portfolio_id: Optional[int] = None
    ) -> int:
        """
        Mark expired signals as EXPIRED.

        Args:
            strategy_id: Optional filter by strategy
            portfolio_id: Optional filter by portfolio

        Returns:
            int: Number of signals expired
        """
        try:
            with self.get_connection() as connection:
                cursor = connection.cursor()

                query = """
                    UPDATE trading_signals
                    SET status = 'EXPIRED', updated_at = NOW()
                    WHERE status = 'PENDING'
                    AND expires_date IS NOT NULL
                    AND expires_date < NOW()
                """
                params = []

                if strategy_id is not None:
                    query += " AND strategy_id = %s"
                    params.append(strategy_id)

                if portfolio_id is not None:
                    query += " AND portfolio_id = %s"
                    params.append(portfolio_id)

                cursor.execute(query, tuple(params))
                expired_count = cursor.rowcount

                if expired_count > 0:
                    logger.info(f"Expired {expired_count} old signals")

                return expired_count

        except mysql.connector.Error as e:
            logger.error(f"Error expiring old signals: {e}")
            return 0

    def get_signal_summary(
        self, portfolio_id: Optional[int] = None, strategy_id: Optional[int] = None
    ) -> Dict:
        """
        Get summary statistics for signals.

        Args:
            portfolio_id: Optional filter by portfolio
            strategy_id: Optional filter by strategy

        Returns:
            Dict containing signal counts and statistics
        """
        try:
            with self.get_connection() as connection:
                cursor = connection.cursor(dictionary=True)

                query = """
                    SELECT
                        COUNT(*) as total_signals,
                        COUNT(CASE WHEN signal_type = 'BUY' THEN 1 END) as buy_signals,
                        COUNT(CASE WHEN signal_type = 'SELL' THEN 1 END) as sell_signals,
                        COUNT(CASE WHEN status = 'PENDING' THEN 1 END) as pending_signals,
                        COUNT(CASE WHEN status = 'ACTED_ON' THEN 1 END) as acted_on_signals,
                        COUNT(CASE WHEN outcome = 'SUCCESS' THEN 1 END) as successful_signals,
                        COUNT(CASE WHEN outcome = 'FAILURE' THEN 1 END) as failed_signals,
                        AVG(confidence_score) as avg_confidence,
                        SUM(profit_loss) as total_profit_loss,
                        AVG(profit_loss) as avg_profit_loss
                    FROM trading_signals
                    WHERE 1=1
                """
                params = []

                if portfolio_id is not None:
                    query += " AND portfolio_id = %s"
                    params.append(portfolio_id)

                if strategy_id is not None:
                    query += " AND strategy_id = %s"
                    params.append(strategy_id)

                cursor.execute(query, tuple(params))
                result = cursor.fetchone()

                # Calculate win rate if applicable
                if result and result["acted_on_signals"] > 0:
                    result["win_rate"] = (
                        result["successful_signals"] / result["acted_on_signals"]
                    ) * 100
                else:
                    result["win_rate"] = None

                return result if result else {}

        except mysql.connector.Error as e:
            logger.error(f"Error retrieving signal summary: {e}")
            return {}

    def check_duplicate_signal(
        self,
        strategy_id: int,
        ticker_id: int,
        signal_date: datetime,
        time_window_hours: int = 24,
    ) -> bool:
        """
        Check if a similar signal already exists within a time window.

        Args:
            strategy_id: Strategy ID
            ticker_id: Ticker ID
            signal_date: Signal date/time
            time_window_hours: Time window in hours to check for duplicates

        Returns:
            bool: True if duplicate exists, False otherwise
        """
        try:
            with self.get_connection() as connection:
                cursor = connection.cursor()

                # Calculate time window
                start_time = signal_date - timedelta(hours=time_window_hours)
                end_time = signal_date + timedelta(hours=time_window_hours)

                query = """
                    SELECT COUNT(*) as count
                    FROM trading_signals
                    WHERE strategy_id = %s
                    AND ticker_id = %s
                    AND signal_date BETWEEN %s AND %s
                    AND status = 'PENDING'
                """
                cursor.execute(query, (strategy_id, ticker_id, start_time, end_time))
                result = cursor.fetchone()

                return result[0] > 0 if result else False

        except mysql.connector.Error as e:
            logger.error(f"Error checking for duplicate signal: {e}")
            return False
